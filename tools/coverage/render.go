package main

import (
	"cmp"
	"fmt"
	"slices"
	"strings"
)

const (
	sectionStart = "<!-- coverage:start -->"
	sectionEnd   = "<!-- coverage:end -->"
	// maxImpactRows caps the "what is dragging coverage down" table.
	maxImpactRows = 10
)

func status(r Report, threshold float64) string {
	if r.Percent() < threshold {
		return fmt.Sprintf("❌ below the %s threshold", formatPct(threshold))
	}
	return fmt.Sprintf("✅ meets the %s threshold", formatPct(threshold))
}

func writeFileTable(b *strings.Builder, files []FileCoverage) {
	b.WriteString("| File | Statements | Covered | Coverage |\n|---|---:|---:|---:|\n")
	for _, f := range files {
		fmt.Fprintf(b, "| `%s` | %d | %d | %s |\n", f.Path, f.Statements, f.Covered, formatPct(f.Percent()))
	}
}

// renderCoverageFile renders COVERAGE.md, the file kept in the repository.
func renderCoverageFile(r Report, threshold float64, ignoreFile string) string {
	var b strings.Builder
	b.WriteString("# Code coverage\n\n")
	b.WriteString("<!-- Generated by tools/coverage in CI. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "**Overall: %s** (%d/%d statements) — %s\n\n",
		formatPct(r.Percent()), r.Covered, r.Statements, status(r, threshold))
	fmt.Fprintf(&b, "Files listed in `%s` are not counted toward the overall percentage.\n\n", ignoreFile)
	b.WriteString("## Files\n\n")
	writeFileTable(&b, r.Files)
	if len(r.Excluded) > 0 {
		fmt.Fprintf(&b, "\n## Excluded via `%s`\n\n", ignoreFile)
		writeFileTable(&b, r.Excluded)
	}
	return b.String()
}

// renderPRSection renders the block placed in the PR description. added is
// nil when there is no diff (e.g. outside a PR).
func renderPRSection(r Report, threshold float64, added map[string]map[int]bool, comments, dropped int) string {
	var b strings.Builder
	b.WriteString(sectionStart + "\n## 🧪 Coverage report\n\n")
	fmt.Fprintf(&b, "**Overall: %s** (%d/%d statements) — %s\n\n",
		formatPct(r.Percent()), r.Covered, r.Statements, status(r, threshold))

	if added != nil {
		var changed []FileCoverage
		for _, f := range r.Files {
			if added[f.Path] != nil {
				changed = append(changed, f)
			}
		}
		b.WriteString("### Files changed in this PR\n\n")
		if len(changed) == 0 {
			b.WriteString("_No covered source files changed._\n\n")
		} else {
			b.WriteString("| File | Coverage | New lines without coverage |\n|---|---:|---:|\n")
			for _, f := range changed {
				fmt.Fprintf(&b, "| `%s` | %s | %d |\n", f.Path, formatPct(f.Percent()), len(uncoveredAdded(f, added[f.Path])))
			}
			b.WriteString("\n")
		}
	}

	if r.Percent() < threshold {
		fmt.Fprintf(&b, "### What is pulling overall coverage down\n\n"+
			"%d more statements need tests to reach %s. "+
			"**Impact** is how much the overall percentage would rise if that file were fully covered.\n\n",
			r.StatementsNeeded(threshold), formatPct(threshold))
		ranked := slices.Clone(r.Files)
		slices.SortStableFunc(ranked, func(a, b FileCoverage) int { return cmp.Compare(b.Missed(), a.Missed()) })
		b.WriteString("| File | Coverage | Uncovered statements | Impact on overall |\n|---|---:|---:|---:|\n")
		rows := 0
		for _, f := range ranked {
			if f.Missed() == 0 || rows == maxImpactRows {
				break
			}
			fmt.Fprintf(&b, "| `%s` | %s | %d | +%.1f pp |\n", f.Path, formatPct(f.Percent()), f.Missed(), r.Impact(f))
			rows++
		}
		b.WriteString("\n")
		if comments > 0 {
			fmt.Fprintf(&b, "Uncovered new lines are marked with %d inline review comment(s).", comments)
			if dropped > 0 {
				fmt.Fprintf(&b, " %d more were not posted to avoid noise.", dropped)
			}
			b.WriteString("\n\n")
		}
	}

	b.WriteString("<details><summary>All files</summary>\n\n")
	writeFileTable(&b, r.Files)
	if len(r.Excluded) > 0 {
		b.WriteString("\nExcluded from the total:\n\n")
		writeFileTable(&b, r.Excluded)
	}
	b.WriteString("\n</details>\n" + sectionEnd + "\n")
	return b.String()
}

// renderText renders a terminal-friendly summary.
func renderText(r Report, threshold float64) string {
	var b strings.Builder
	width := len("TOTAL")
	for _, f := range append(slices.Clone(r.Files), r.Excluded...) {
		width = max(width, len(f.Path))
	}
	for _, f := range r.Files {
		fmt.Fprintf(&b, "%-*s %7s\n", width, f.Path, formatPct(f.Percent()))
	}
	for _, f := range r.Excluded {
		fmt.Fprintf(&b, "%-*s %7s  (excluded)\n", width, f.Path, formatPct(f.Percent()))
	}
	fmt.Fprintf(&b, "%-*s %7s  %s\n", width, "TOTAL", formatPct(r.Percent()), status(r, threshold))
	return b.String()
}
